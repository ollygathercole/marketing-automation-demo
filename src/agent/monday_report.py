from datetime import date
from pathlib import Path

from src.agent.ask_claude import ask

PROMPT = """Write the weekly briefing for the Veridian Optics commercial team.
Do not include a title, and do not mention a day of the week or a date for the briefing itself. The file adds those. You may state the data_as_of date from the tools.
This report may run to about 700 words. Structure it exactly like this:

Start with a headline of two sentences: the most important thing in consumables and the most important thing in marketing.

## 1. Consumables
- State how many accounts have a gap at the 6 month threshold, and how many of those have a recorded clinical lead change and how many do not.
- A table of exactly 8 accounts to contact this week: the 5 lead-change accounts with the biggest fall in monthly order value, then the 3 accounts with no lead change that have the most devices with a gap and the longest time since their last order. Columns: account name and ID, what changed, suggested first question. Describe how you chose them in one sentence at most, without using the word "I".
- One line on probable false alarms: an account with exactly one device gap that has ordered in the last 30 days. Give the count and state this definition in the same line.
- Accounts with no order on record are not false alarms. Say how many there are and describe them as owning devices but never having ordered consumables. Use get_account_detail on one of them and give the oldest device install year as an example.

## 2. Marketing
- The latest four weeks against the previous four weeks, in a short table.
- Whether webinar attendees request demos more than other contacts, with the caveat on cause. Label the webinar table "All time" and make clear it is separate from the four-week table above it, which covers only recent weeks.

## 3. Three actions for this week
Numbered, each one specific enough to start on Monday morning.

Where you describe an account as still ordering, give the date of its last order. Do not call missing order history a data error unless the tools show evidence of one.
Use only numbers from the tools. Mark inferences as inferences. Do not recommend actions that need data the tools do not return, such as lists of contacts who did not click or who did not attend."""


def main():
    today = date.today().isoformat()
    body = ask(PROMPT, max_steps=12)

    out_dir = Path("reports")
    out_dir.mkdir(exist_ok=True)
    path = out_dir / f"monday_report_{today}.md"

    header = f"# Veridian Optics: weekly commercial briefing, {today}\n\n"
    footer = (
        "\n\n---\n*Generated by Claude using fixed, read-only BigQuery tools. "
        "Veridian Optics and all data are fictional.*\n"
    )
    path.write_text(header + body + footer, encoding="utf-8")
    print()
    print("Saved", path)


if __name__ == "__main__":
    main()